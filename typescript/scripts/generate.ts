import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const check = process.argv.includes('--check');
const specText = await readFile(new URL('../../openapi.json', import.meta.url), 'utf8');
const header = '// Generated by scripts/generate.ts from ../openapi.json. Do not edit.\n';

const types =
  header +
  astToString(
    await openapiTS(specText, {
      alphabetize: true,
      rootTypes: true,
      rootTypesNoSchemaPrefix: true,
    }),
  );

const spec = JSON.parse(specText) as {
  components: { schemas: Record<string, unknown> };
  paths: Record<string, Record<string, OpenApiOperation>>;
};
type OpenApiOperation = {
  operationId: string;
  parameters?: { in: string; name: string }[];
  'x-extralt-idempotent': boolean;
};
const entries: string[] = [];
for (const [path, item] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b))) {
  for (const method of ['get', 'put', 'post', 'delete', 'patch']) {
    const operation = item[method];
    if (!operation) continue;
    const idempotencyKey = (operation.parameters ?? []).some(
      (parameter) =>
        parameter.in === 'header' && parameter.name.toLowerCase() === 'idempotency-key',
    );
    entries.push(
      `  ${operation.operationId}: { method: '${method.toUpperCase()}', path: '${path}', idempotent: ${operation['x-extralt-idempotent']}, idempotencyKey: ${idempotencyKey} },`,
    );
  }
}
const operations = `${header}import type { Operation } from '../core/operation.js';
import type { operations } from './openapi.js';

export const OPERATIONS: { readonly [K in keyof operations]: Operation } = {
${entries.join('\n')}
};
`;

// The package exports the API's schemas by name and nothing shaped by the type generator, so the
// generator can be replaced without changing the public types.
const schemaNames = Object.keys(spec.components.schemas).sort((a, b) => a.localeCompare(b));
const schemas = `${header}export type {
${schemaNames.map((name) => `  ${name},`).join('\n')}
} from './openapi.js';
`;

const outputs = new Map([
  [new URL('../src/generated/openapi.ts', import.meta.url), types],
  [new URL('../src/generated/operations.ts', import.meta.url), operations],
  [new URL('../src/generated/schemas.ts', import.meta.url), schemas],
]);
const stale: string[] = [];
for (const [url, contents] of outputs) {
  if (check) {
    const existing = await readFile(url, 'utf8').catch(() => '');
    if (existing !== contents) stale.push(url.pathname);
  } else {
    await writeFile(url, contents);
  }
}
if (stale.length > 0) throw new Error(`Generated sources are stale: ${stale.join(', ')}`);
console.log(check ? 'Generated sources match openapi.json.' : 'Wrote src/generated/');
