"""Generates the SDK's derived sources from ../openapi.json and the async client.

- src/extralt/types.py: response and request models (datamodel-code-generator), with the API's
  decimal strings as `Decimal`
- src/extralt/_operations.py: method, path and retry safety per operation
- src/extralt/_sync/: the synchronous client, rewritten from src/extralt/_async/ by unasync

Run `uv run scripts/generate.py`, or add `--check` to fail when any output is stale.
"""

from __future__ import annotations

import filecmp
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import unasync

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT.parent / "openapi.json"
PACKAGE = ROOT / "src" / "extralt"
METHODS = ("get", "put", "post", "delete", "patch")
# Prices, price differences and ratios: digits with an optional sign and fraction.
DECIMAL_PATTERN = re.compile(
    r"\^(?:-\?)?\(0\|\[1-9\]\[0-9\]\{0,\d+\}\)\(\\\.\[0-9\]\{1,\d+\}\)\?\$"
)
HEADER = "# Generated by scripts/generate.py from {source}. Do not edit.\n"


def generate(package: Path) -> None:
    generate_types(package / "types.py")
    generate_operations(package / "_operations.py")
    generate_sync(package / "_async", package / "_sync")
    ruff = ["ruff", "--config", str(ROOT / "pyproject.toml")]
    outputs = [str(package / "_operations.py"), str(package / "_sync")]
    subprocess.run(
        [ruff[0], "format", *ruff[1:], "--quiet", str(package / "types.py"), *outputs], check=True
    )
    # Generated from async generators, which cannot use `yield from`.
    check = [ruff[0], "check", *ruff[1:], "--quiet", "--fix", "--ignore", "UP028"]
    subprocess.run([*check, *outputs], check=True)
    subprocess.run([ruff[0], "format", *ruff[1:], "--quiet", *outputs], check=True)


def decimal_strings(schema: object) -> object:
    """Types the API's decimal strings as decimals, so they compare and add as numbers."""
    if isinstance(schema, list):
        return [decimal_strings(item) for item in schema]
    if not isinstance(schema, dict):
        return schema
    schema = {key: decimal_strings(value) for key, value in schema.items()}
    if DECIMAL_PATTERN.fullmatch(str(schema.get("pattern", ""))):
        del schema["pattern"]
        schema["format"] = "decimal"
    return schema


def generate_types(output: Path) -> None:
    with tempfile.TemporaryDirectory() as directory:
        spec = Path(directory) / "openapi.json"
        spec.write_text(json.dumps(decimal_strings(json.loads(SPEC.read_text()))))
        _generate_types(spec, output)


def _generate_types(spec: Path, output: Path) -> None:
    subprocess.run(
        [
            "datamodel-codegen",
            "--input",
            str(spec),
            "--input-file-type",
            "openapi",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.11",
            "--use-annotated",
            "--use-standard-collections",
            "--use-union-operator",
            "--enum-field-as-literal",
            "all",
            "--field-constraints",
            "--use-double-quotes",
            "--disable-timestamp",
            "--use-schema-description",
            "--use-field-description",
            "--use-type-alias",
            "--extra-fields",
            "allow",
            "--formatters",
            "ruff-format",
            "ruff-check",
            "--custom-file-header",
            HEADER.format(source="openapi.json").rstrip("\n"),
        ],
        check=True,
        capture_output=True,
    )


def generate_operations(output: Path) -> None:
    spec = json.loads(SPEC.read_text())
    lines = [
        HEADER.format(source="openapi.json"),
        "from ._operation import Operation\n",
        "OPERATIONS: dict[str, Operation] = {",
    ]
    for path, item in sorted(spec["paths"].items()):
        for method in METHODS:
            operation = item.get(method)
            if operation is None:
                continue
            idempotency_key = any(
                parameter.get("in") == "header"
                and parameter.get("name", "").lower() == "idempotency-key"
                for parameter in operation.get("parameters", [])
            )
            lines.append(
                f"    {operation['operationId']!r}: Operation({method.upper()!r}, {path!r}, "
                f"idempotent={operation['x-extralt-idempotent']}, "
                f"idempotency_key={idempotency_key}),"
            )
    lines.append("}\n")
    output.write_text("\n".join(lines))


def generate_sync(source: Path, target: Path) -> None:
    files = sorted(source.rglob("*.py"))
    names = set()
    for file in files:
        names.update(re.findall(r"\bAsync[A-Z]\w*", file.read_text()))
    replacements = {name: name.removeprefix("Async") for name in names}
    replacements.update(
        {
            "AsyncHTTP": "SyncHTTP",
            "aclose": "close",
            "aread": "read",
            "aiter_bytes": "iter_bytes",
            "awrite_chunks": "write_chunks",
            "anyio": "time",
        }
    )
    shutil.rmtree(target, ignore_errors=True)
    rule = unasync.Rule(
        fromdir=str(source) + "/",
        todir=str(target) + "/",
        additional_replacements=replacements,
    )
    unasync.unasync_files([str(file) for file in files], rules=[rule])
    for file in target.rglob("*.py"):
        file.write_text(HEADER.format(source="../_async") + file.read_text())


def main() -> None:
    if "--check" not in sys.argv[1:]:
        generate(PACKAGE)
        print("Generated types.py, _operations.py and _sync/")
        return
    # Inside the project, so the formatters resolve the same configuration as in place.
    with tempfile.TemporaryDirectory(dir=ROOT, prefix=".generate-check-") as directory:
        copy = Path(directory) / "extralt"
        shutil.copytree(PACKAGE, copy)
        generate(copy)
        comparison = filecmp.dircmp(PACKAGE, copy)
        stale = _differences(comparison)
    if stale:
        raise SystemExit("Generated sources are stale: " + ", ".join(stale))
    print("Generated sources match openapi.json and _async/")


def _differences(comparison: filecmp.dircmp[str]) -> list[str]:
    stale = list(comparison.diff_files) + list(comparison.left_only) + list(comparison.right_only)
    for name, sub in comparison.subdirs.items():
        stale.extend(f"{name}/{item}" for item in _differences(sub))
    return [name for name in stale if name != "__pycache__"]


if __name__ == "__main__":
    main()
